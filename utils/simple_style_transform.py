"""

Ce script introduit les transformations :
 - GreyScale
 - Silhouette
 - Edges

pour pouvoir transformer nos images dans le format voulut.


Greyscale  : experiment This experiment used the same images as the original experiment with the
difference that they were converted to greyscale using skimage.color.rgb2gray. For CNNs,
greyscale images were stacked three times along the colour channel.


Silhouette : experiment The images from the original experiment were transformed into silhouette
images showing an entirely black object on a white background. We used the following transfor-
mation procedure: First, images were converted to bmp using command line utility (convert).
They were then converted to svg using potrace, and then to png using convert again. Since
an entirely automatic binarization pipeline is not feasible (it takes domain knowledge to understand
that a car wheel should, but a doughnut should not be filled with black colour), we then manually
checked every single image and adapted the silhouette using GIMP if necessary.


Edge : experiment The stimuli shown in this condition were generated by applying the “Canny”
edge extractor implemented in MATLAB (Release 2016a, The MathWorks, Inc., Natick, Mas-
sachusetts, United States) to the images used in the original experiment. No further manipulations
were performed on this data set. This line of code was used to detect edges and generate the stimuli
used in this experiment:
imwrite(1-edge(imgaussfilt(rgb2gray(imread(filename)), 2),
’Canny’), targetFilename);


"""

from __future__ import annotations

import numpy as np
from PIL import Image, ImageFilter


def _to_rgb_array(img: Image.Image | np.ndarray) -> np.ndarray:
    """Convert PIL.Image or ndarray to float32 RGB array in [0, 1] of shape (H, W, 3)."""
    if isinstance(img, Image.Image):
        arr = np.asarray(img.convert("RGB"), dtype=np.float32) / 255.0
    elif isinstance(img, np.ndarray):
        arr = img.astype(np.float32)
        if arr.max() > 1.0:
            arr = arr / 255.0
        if arr.ndim == 2:
            arr = np.stack([arr, arr, arr], axis=-1)
    else:
        raise TypeError(f"Type d'image non supporté : {type(img).__name__}")
    return arr


def _rgb_to_gray(rgb: np.ndarray) -> np.ndarray:
    """Luminance conversion matching skimage.color.rgb2gray."""
    return 0.2125 * rgb[..., 0] + 0.7154 * rgb[..., 1] + 0.0721 * rgb[..., 2]


def _gaussian_kernel_1d(sigma: float) -> np.ndarray:
    radius = max(1, int(np.ceil(3.0 * sigma)))
    x = np.arange(-radius, radius + 1, dtype=np.float32)
    kernel = np.exp(-(x**2) / (2.0 * sigma**2))
    return kernel / kernel.sum()


def _gaussian_blur(gray: np.ndarray, sigma: float = 2.0) -> np.ndarray:
    if sigma <= 0:
        return gray
    k = _gaussian_kernel_1d(sigma)
    r = len(k) // 2
    padded_h = np.pad(gray, ((r, r), (0, 0)), mode="reflect")
    blur_h = np.apply_along_axis(lambda m: np.convolve(m, k, mode="valid"), 0, padded_h)
    padded_w = np.pad(blur_h, ((0, 0), (r, r)), mode="reflect")
    return np.apply_along_axis(lambda m: np.convolve(m, k, mode="valid"), 1, padded_w)


def _otsu_threshold(values: np.ndarray, bins: int = 256) -> float:
    hist, bin_edges = np.histogram(values.ravel(), bins=bins, range=(0.0, 1.0))
    hist = hist.astype(np.float64)
    total = hist.sum()
    if total == 0:
        return 0.5

    bin_centers = 0.5 * (bin_edges[:-1] + bin_edges[1:])
    weight1 = np.cumsum(hist)
    weight2 = total - weight1
    mean1 = np.cumsum(hist * bin_centers) / np.maximum(weight1, 1e-12)
    mean2 = (np.cumsum((hist * bin_centers)[::-1])[::-1]) / np.maximum(weight2, 1e-12)

    between_var = weight1[:-1] * weight2[1:] * (mean1[:-1] - mean2[1:]) ** 2
    idx = int(np.argmax(between_var))
    return float(bin_centers[idx])


class GreyScale:
    """Convert image to luminance greyscale and stack 3 times along RGB channels."""

    def __call__(self, img: Image.Image | np.ndarray) -> Image.Image:
        rgb = _to_rgb_array(img)
        gray = _rgb_to_gray(rgb)
        gray_u8 = np.clip(gray * 255.0, 0, 255).astype(np.uint8)
        stacked = np.stack([gray_u8, gray_u8, gray_u8], axis=-1)
        return Image.fromarray(stacked, mode="RGB")


class Silhouette:
    """Approximate object silhouette (black foreground on white background)."""

    def __init__(self, blur_sigma: float = 1.5, border_fraction: float = 0.08) -> None:
        self.blur_sigma = blur_sigma
        self.border_fraction = border_fraction

    def __call__(self, img: Image.Image | np.ndarray) -> Image.Image:
        rgb = _to_rgb_array(img)
        h, w, _ = rgb.shape
        bh = max(1, int(h * self.border_fraction))
        bw = max(1, int(w * self.border_fraction))

        border_pixels = np.concatenate(
            [
                rgb[:bh, :, :].reshape(-1, 3),
                rgb[-bh:, :, :].reshape(-1, 3),
                rgb[:, :bw, :].reshape(-1, 3),
                rgb[:, -bw:, :].reshape(-1, 3),
            ],
            axis=0,
        )
        bg_color = np.median(border_pixels, axis=0)
        dist = np.linalg.norm(rgb - bg_color, axis=-1)
        max_dist = float(dist.max())
        if max_dist > 1e-6:
            dist = dist / max_dist

        dist_smooth = _gaussian_blur(dist, sigma=self.blur_sigma)
        thresh = _otsu_threshold(dist_smooth)
        fg_mask = dist_smooth > thresh

        # Light morphological smoothing (closing then opening) via PIL filters
        mask_img = Image.fromarray((fg_mask.astype(np.uint8)) * 255, mode="L")
        mask_img = mask_img.filter(ImageFilter.MaxFilter(3)).filter(
            ImageFilter.MinFilter(3)
        )
        mask_img = mask_img.filter(ImageFilter.MinFilter(3)).filter(
            ImageFilter.MaxFilter(3)
        )

        # Black object (0) on white background (255)
        silhouette_arr = np.where(np.asarray(mask_img) > 127, 0, 255).astype(np.uint8)
        stacked = np.stack([silhouette_arr, silhouette_arr, silhouette_arr], axis=-1)
        return Image.fromarray(stacked, mode="RGB")


class Edges:
    """Canny edge detector with Gaussian pre-filter (black edges on white background)."""

    def __init__(
        self,
        sigma: float = 2.0,
        low_ratio: float = 0.08,
        high_ratio: float = 0.20,
    ) -> None:
        self.sigma = sigma
        self.low_ratio = low_ratio
        self.high_ratio = high_ratio

    def __call__(self, img: Image.Image | np.ndarray) -> Image.Image:
        rgb = _to_rgb_array(img)
        gray = _rgb_to_gray(rgb)
        blurred = _gaussian_blur(gray, sigma=self.sigma)

        # Sobel gradients
        p = np.pad(blurred, 1, mode="reflect")
        gx = (
            (p[:-2, 2:] + 2.0 * p[1:-1, 2:] + p[2:, 2:])
            - (p[:-2, :-2] + 2.0 * p[1:-1, :-2] + p[2:, :-2])
        )
        gy = (
            (p[2:, :-2] + 2.0 * p[2:, 1:-1] + p[2:, 2:])
            - (p[:-2, :-2] + 2.0 * p[:-2, 1:-1] + p[:-2, 2:])
        )

        mag = np.hypot(gx, gy)
        angle = (np.rad2deg(np.arctan2(gy, gx)) + 180.0) % 180.0

        # Non-maximum suppression
        h, w = mag.shape
        nms = np.zeros_like(mag)
        m = np.pad(mag, 1, mode="constant")

        dir0 = ((angle < 22.5) | (angle >= 157.5))
        dir45 = ((angle >= 22.5) & (angle < 67.5))
        dir90 = ((angle >= 67.5) & (angle < 112.5))
        dir135 = ((angle >= 112.5) & (angle < 157.5))

        c = m[1:-1, 1:-1]
        keep0 = dir0 & (c >= m[1:-1, 2:]) & (c >= m[1:-1, :-2])
        keep45 = dir45 & (c >= m[:-2, 2:]) & (c >= m[2:, :-2])
        keep90 = dir90 & (c >= m[:-2, 1:-1]) & (c >= m[2:, 1:-1])
        keep135 = dir135 & (c >= m[:-2, :-2]) & (c >= m[2:, 2:])

        keep = keep0 | keep45 | keep90 | keep135
        nms[keep] = mag[keep]

        # Double threshold + hysteresis
        max_mag = float(nms.max())
        if max_mag <= 1e-8:
            white = np.full((h, w, 3), 255, dtype=np.uint8)
            return Image.fromarray(white, mode="RGB")

        high_t = max_mag * self.high_ratio
        low_t = max_mag * self.low_ratio

        strong = nms >= high_t
        weak = (nms >= low_t) & ~strong

        edges = strong.copy()
        # Propagate strong edges to connected weak edges (iterative 8-connectivity)
        changed = True
        while changed:
            ep = np.pad(edges, 1, mode="constant")
            neighbors = (
                ep[:-2, :-2]
                | ep[:-2, 1:-1]
                | ep[:-2, 2:]
                | ep[1:-1, :-2]
                | ep[1:-1, 2:]
                | ep[2:, :-2]
                | ep[2:, 1:-1]
                | ep[2:, 2:]
            )
            new_edges = edges | (weak & neighbors)
            changed = bool(np.any(new_edges != edges))
            edges = new_edges

        # 1 - edge: black edges (0) on white background (255)
        edge_u8 = np.where(edges, 0, 255).astype(np.uint8)
        stacked = np.stack([edge_u8, edge_u8, edge_u8], axis=-1)
        return Image.fromarray(stacked, mode="RGB")

